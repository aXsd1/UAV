"""Generate the PX4 SITL airframe for the vehicle from the config and aero tables.

python -m tools.px4gen  ->  px4/airframes/4050_gz_vtol_p1

Frames (PX4 tailsitter): allocation works in the hover (multicopter) body frame
FRD, where x_mc = fixed-wing z (belly), y_mc = fixed-wing y, z_mc = -fixed-wing x
(nose). So vane "pitch" acts on MC pitch, vane "yaw" (fixed-wing yaw) on MC
roll, rotor torque difference on MC yaw, elevon roll on -MC yaw.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

from tools.aerogen import config

ROOT = Path(__file__).resolve().parents[1]
AIRFRAME_ID = 4050


def build(cfg: dict, aero: dict, rotor_rows: list[tuple[float, float, float]]) -> str:
    name = f"vtol_{cfg['meta']['name']}"
    g = cfg["environment"]["gravity_m_s2"]
    weight = aero["mass"]["mass_kg"] * g
    tw = cfg["rotors"]["max_thrust_to_weight"]
    _, ct0, cq0 = rotor_rows[0]
    km = cq0 * aero["rotor"]["diameter_m"] / ct0            # torque / thrust, static
    ct_param = tw * weight / 2.0                              # N per rotor at full output
    w_max = aero["rotor"]["max_rpm"] * 2 * math.pi / 60.0
    vmax = aero["vanes"]["max_deflection_deg"]
    emax = aero["elevons"]["max_deflection_deg"]
    # Hover moment of one vane axis at full deflection (N m); the hover matrix is normalised,
    # so only its ratio to the rotor torque (CT * KM) matters.
    vane_full = aero["hover_allocation"]["pitch_yaw_moment_per_vane_rad_nm"] * math.radians(vmax)
    hover_thr = 1.0 / tw  # thrust is linearised (THR_MDL_FAC 1), so normalised hover thrust = W / T_max

    return f"""#!/bin/sh
#
# @name Ducted coaxial tail-sitter {cfg['meta']['name'].upper()} (Gazebo)
#
# @type VTOL Tailsitter
#
# @maintainer UAV project
#
# Generated by tools/px4gen.py from config/{cfg['_source']['file']}; do not edit.
# Needs the CA_TS_MC_SV control-allocation patch (px4/patches).
#

. ${{R}}etc/init.d/rc.vtol_defaults

PX4_SIMULATOR=${{PX4_SIMULATOR:=gz}}
PX4_GZ_WORLD=${{PX4_GZ_WORLD:=default}}
PX4_SIM_MODEL=${{PX4_SIM_MODEL:={name}}}

param set-default SIM_GZ_EN 1
param set-default MAV_TYPE 19   # VTOL tailsitter, duo rotor

# --- Control allocation: hover matrix = 2 coaxial rotors + 2 exit vanes ---------------
param set-default CA_AIRFRAME 4
param set-default CA_TS_MC_SV 2

param set-default CA_ROTOR_COUNT 2
param set-default CA_ROTOR0_PX 0
param set-default CA_ROTOR0_PY 0
param set-default CA_ROTOR0_CT {ct_param:.1f}
param set-default CA_ROTOR0_KM {km:.4f}    # upper, CCW seen from the nose
param set-default CA_ROTOR1_PX 0
param set-default CA_ROTOR1_PY 0
param set-default CA_ROTOR1_CT {ct_param:.1f}
param set-default CA_ROTOR1_KM {-km:.4f}   # lower, CW
param set-default THR_MDL_FAC 1           # thrust ~ (motor speed)^2

param set-default CA_SV_CS_COUNT 4
param set-default CA_SV_CS0_TYPE 12       # vane, pitch axis (hover matrix)
param set-default CA_SV_CS0_TRQ_P {vane_full:.3f}
param set-default CA_SV_CS1_TYPE 12       # vane, fixed-wing yaw axis = MC roll (hover matrix)
param set-default CA_SV_CS1_TRQ_R {vane_full:.3f}
param set-default CA_SV_CS2_TYPE 12       # left elevon (forward-flight matrix)
param set-default CA_SV_CS2_TRQ_P -0.5
param set-default CA_SV_CS2_TRQ_Y -0.5
param set-default CA_SV_CS3_TYPE 12       # right elevon
param set-default CA_SV_CS3_TRQ_P -0.5
param set-default CA_SV_CS3_TRQ_Y 0.5

# --- Gazebo outputs ------------------------------------------------------------------
param set-default SIM_GZ_EC_FUNC1 101
param set-default SIM_GZ_EC_FUNC2 102
param set-default SIM_GZ_EC_MIN1 0
param set-default SIM_GZ_EC_MIN2 0
param set-default SIM_GZ_EC_MAX1 {w_max:.0f}
param set-default SIM_GZ_EC_MAX2 {w_max:.0f}

param set-default SIM_GZ_SV_FUNC1 201
param set-default SIM_GZ_SV_FUNC2 202
param set-default SIM_GZ_SV_FUNC3 203
param set-default SIM_GZ_SV_FUNC4 204
param set-default SIM_GZ_SV_MINA1 {-vmax:.0f}
param set-default SIM_GZ_SV_MAXA1 {vmax:.0f}
param set-default SIM_GZ_SV_MINA2 {-vmax:.0f}
param set-default SIM_GZ_SV_MAXA2 {vmax:.0f}
param set-default SIM_GZ_SV_MINA3 {-emax:.0f}
param set-default SIM_GZ_SV_MAXA3 {emax:.0f}
param set-default SIM_GZ_SV_MINA4 {-emax:.0f}
param set-default SIM_GZ_SV_MAXA4 {emax:.0f}

# --- Hover control (first-cut gains, to be tuned in SITL) ---------------------------------
param set-default MPC_THR_HOVER {hover_thr:.2f}
param set-default MC_ROLL_P 4
param set-default MC_PITCH_P 4
param set-default MC_YAW_P 2
# Vane authority is ~5 rad/s^2 per unit torque setpoint (I ~ 1 kg m^2), so the rate loop needs
# P ~ 2.5 for a ~12 rad/s crossover, well above the attitude loop (P 4).
param set-default MC_ROLLRATE_P 2.5
param set-default MC_ROLLRATE_I 0.8
param set-default MC_ROLLRATE_D 0.04
param set-default MC_PITCHRATE_P 2.5
param set-default MC_PITCHRATE_I 0.8
param set-default MC_PITCHRATE_D 0.04
param set-default MC_YAWRATE_P 0.4
param set-default MC_YAWRATE_I 0.1
param set-default MC_AIRMODE 1

# --- VTOL / forward flight --------------------------------------------------------
param set-default VT_TYPE 0
param set-default VT_ELEV_MC_LOCK 1
# No rudder: fixed-wing yaw goes to the hover matrix (vane yaw) through the differential-thrust path.
param set-default VT_FW_DIFTHR_EN 1
param set-default VT_FW_DIFTHR_S_Y 1
param set-default VT_ARSP_TRANS {cfg['requirements']['cruise_speed_m_s'] - 4:.0f}
param set-default VT_F_TRANS_DUR 3
param set-default VT_B_TRANS_DUR 5
param set-default FW_AIRSPD_STALL 12
param set-default FW_AIRSPD_MIN 15
param set-default FW_AIRSPD_TRIM {cfg['requirements']['cruise_speed_m_s']:.0f}
param set-default FW_AIRSPD_MAX 28
# Weathervane side-on (px4/patches/0002): wing edge-on to the wind in hover, so less lean
# and the wind on a leg axis at touchdown.
param set-default WV_EN 1
param set-default WV_AXIS 1
param set-default WV_ROLL_MIN 2
param set-default WV_YRATE_MAX 10
param set-default MPC_LAND_SPEED 0.5
param set-default EKF2_FUSE_BETA 0
"""


def main() -> int:
    cfg = config.load(ROOT / "config" / "p1.toml")
    tables = ROOT / "models" / "aero" / cfg["meta"]["name"]
    aero = json.loads((tables / "aero.json").read_text(encoding="utf-8"))
    rows = [tuple(map(float, line.split(","))) for line in
            (tables / "rotor.csv").read_text(encoding="utf-8").splitlines()[1:]]
    out = ROOT / "px4" / "airframes" / f"{AIRFRAME_ID}_gz_vtol_{cfg['meta']['name']}"
    out.write_text(build(cfg, aero, rows), encoding="utf-8", newline="\n")
    print(f"airframe written to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
